"""Lab-local VCP dependency environment -- OFFLINE, EXACT WHEEL, ISOLATED

Character Lab pinned VCP dependency consumption (LAB VCP DEPENDENCY ENV).

Creates build/output/lab_vcp_env/, a Lab-local Python environment that contains
the exact voyage-character-platform wheel produced by the pinned dependency
build (build/scripts/build_vcp_shared_core.py), so Lab publication tests can
import ``voyage_character_platform`` without the live VCP working tree.

Adapted from the proven Studio pattern
(STUDIO_J1B_0_VCP_DEPENDENCY_CONSUMPTION_V1). This script is intentionally
narrow and is NOT a dependency manager and NOT the production desktop
distribution mechanism.

Guarantees:
  - Dependency identity comes ONLY from the tracked provenance
    (build/provenance/vcp_shared_core_provenance.json). No wheel hash is
    duplicated here.
  - The wheel is the generated artifact beneath build/output/; its filename
    and SHA-256 must match the provenance exactly.
  - pip always runs inside the generated environment with --no-index,
    --no-deps, --disable-pip-version-check and --no-cache-dir. Never editable;
    never from source; never from the VCP working tree.
  - The environment is fully isolated (no --system-site-packages) and lives
    beneath build/output/ (gitignored). The base interpreter is never modified.
  - PYTHONPATH is scrubbed from every subprocess.
  - Refuses to proceed on any mismatch (fail closed).
  - Never commits, stages, pushes or merges.

Prerequisite (generated by the pinned build, not fetched here):
  build/output/vcp_shared_core/voyage_character_platform-0.1.0-py3-none-any.whl
  (run build/scripts/build_vcp_shared_core.py first if it is absent)

USAGE:
  py build/scripts/bootstrap_lab_vcp_env.py

Invoking Lab processes afterwards (no activation required), from the Lab
repository root:
  build/output/lab_vcp_env/Scripts/python.exe -E -s <script or -m module>

``-E`` ignores PYTHON* variables and ``-s`` ignores the user site, so no
PYTHONPATH can inject a VCP source tree. Lab source resolves through the
ordinary current-working-directory entry on sys.path; voyage_character_platform
resolves from the environment's site-packages.
"""

import argparse
import importlib.util
import json
import re
import shutil
import sys
from pathlib import Path

# =============================================================================
# Reuse the pinned build (constants, layout and fail-closed helpers)
# =============================================================================

_J1A_SCRIPT = Path(__file__).resolve().parent / "build_vcp_shared_core.py"


def _load_j1a():
    spec = importlib.util.spec_from_file_location("build_vcp_shared_core", _J1A_SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


j1a = _load_j1a()
BootstrapError = j1a.BootstrapError

LAB_ENV_DIRNAME = "lab_vcp_env"

# Extra pip flags on top of J1A's PIP_OFFLINE_ARGS (--no-index --no-deps
# --disable-pip-version-check).
PIP_EXTRA_ARGS = ["--no-cache-dir"]

# Distributions permitted inside the generated environment.
EXPECTED_ENV_DISTRIBUTIONS = frozenset({"pip", j1a.DEPENDENCY_NAME})

_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")


# =============================================================================
# Dependency identity (provenance is authoritative)
# =============================================================================


def provenance_path(repo_root):
    return Path(repo_root).joinpath(*j1a.PROVENANCE_RELPATH)


def load_dependency_identity(path):
    """Read and validate the pinned-build provenance. Return the identity."""
    path = Path(path)
    if not path.is_file():
        raise BootstrapError(f"VCP provenance not found: {path}")
    record = json.loads(path.read_text(encoding="utf-8"))
    expected = {
        "schema_version": j1a.PROVENANCE_SCHEMA_VERSION,
        "dependency_name": j1a.DEPENDENCY_NAME,
        "dependency_version": j1a.DEPENDENCY_VERSION,
        "source_repository": j1a.VCP_SOURCE_REPOSITORY,
        "source_commit": j1a.VCP_SOURCE_COMMIT,
        "wheel_filename": j1a.EXPECTED_WHEEL_FILENAME,
        "build_command_digest": j1a.build_command_digest(),
    }
    for key, value in expected.items():
        if record.get(key) != value:
            raise BootstrapError(
                f"Provenance mismatch for {key}: "
                f"expected {value!r}, got {record.get(key)!r}"
            )
    wheel_sha256 = record.get("wheel_sha256")
    if not isinstance(wheel_sha256, str) or not _SHA256_RE.match(wheel_sha256):
        raise BootstrapError(f"Provenance wheel_sha256 malformed: {wheel_sha256!r}")
    return {
        "dependency_name": record["dependency_name"],
        "dependency_version": record["dependency_version"],
        "import_package": j1a.IMPORT_PACKAGE,
        "source_commit": record["source_commit"],
        "wheel_filename": record["wheel_filename"],
        "wheel_sha256": wheel_sha256,
    }


def verify_wheel(wheel_path, identity):
    """Exact filename and SHA-256 against the provenance identity."""
    wheel_path = Path(wheel_path)
    if wheel_path.name != identity["wheel_filename"]:
        raise BootstrapError(
            f"Wheel filename mismatch: {wheel_path.name} != {identity['wheel_filename']}"
        )
    if not wheel_path.is_file() or wheel_path.is_symlink():
        raise BootstrapError(
            f"VCP wheel missing or not a regular file: {wheel_path}\n"
            "  Run build/scripts/build_vcp_shared_core.py first."
        )
    actual = j1a.sha256_file(wheel_path)
    if actual != identity["wheel_sha256"]:
        raise BootstrapError(
            f"{wheel_path.name} SHA-256 MISMATCH\n"
            f"  Expected: {identity['wheel_sha256']}\n"
            f"  Got:      {actual}"
        )
    print(f"{wheel_path.name} SHA-256 verified against provenance: {actual}\n")
    return wheel_path


# =============================================================================
# Generated environment
# =============================================================================


def lab_env_dir(repo_root):
    return j1a.output_root(repo_root) / LAB_ENV_DIRNAME


def venv_create_command(env_dir):
    """Isolated venv; pip comes from the wheel bundled with CPython (offline)."""
    return [sys.executable, "-m", "venv", str(env_dir)]


def install_command(py, wheel_path):
    return (
        [str(py), "-I", "-m", "pip", "install"]
        + j1a.PIP_OFFLINE_ARGS
        + PIP_EXTRA_ARGS
        + [str(wheel_path)]
    )


def create_env(repo_root, env_dir, temp_dir):
    env_dir = j1a.ensure_under_output(repo_root, env_dir)
    if env_dir == j1a.output_root(repo_root).resolve():
        raise BootstrapError("Refusing to use build/output/ itself as the environment")
    if env_dir.exists():
        shutil.rmtree(env_dir)
    j1a.run_cmd(
        venv_create_command(env_dir),
        "CREATE LAB VCP ENV",
        env=j1a.subprocess_env(temp_dir=temp_dir),
    )
    return env_dir, j1a.env_python(env_dir)


def install_wheel(py, wheel_path, temp_dir):
    j1a.run_cmd(
        install_command(py, wheel_path),
        "INSTALL EXACT VCP WHEEL (OFFLINE, NO DEPS)",
        env=j1a.subprocess_env(temp_dir=temp_dir),
    )


