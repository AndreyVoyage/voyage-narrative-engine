# Consumption smoke
# =============================================================================

# Runs inside the generated environment with -E -s and cwd=<Lab root>.
# It only collects facts; every decision is made by validate_smoke_report().
SMOKE_SCRIPT = """
import importlib.metadata as md
import json
import sys

import voyage_character_platform as vcp
from voyage_character_platform import package_v1
import services.character_publication.vcp_release as lab_probe

dist = md.distribution("voyage-character-platform")
report = {
    "python_version": sys.version.split()[0],
    "prefix": sys.prefix,
    "base_prefix": sys.base_prefix,
    "module_file": vcp.__file__,
    "lab_probe_file": lab_probe.__file__,
    "dist_name": dist.metadata["Name"],
    "dist_version": dist.version,
    "direct_url": json.loads(dist.read_text("direct_url.json") or "{}"),
    "verify_package_v1_public": callable(getattr(vcp, "verify_package_v1", None))
        and "verify_package_v1" in getattr(vcp, "__all__", ()),
    "verify_package_v1_module": getattr(vcp, "verify_package_v1", None)
        is getattr(package_v1, "verify_package_v1", object()),
    "distributions": sorted({d.metadata["Name"].lower() for d in md.distributions()}),
    "no_user_site": bool(sys.flags.no_user_site),
    "ignore_environment": bool(sys.flags.ignore_environment),
}
print(json.dumps(report, sort_keys=True))
"""


def smoke_command(py):
    return [str(py), "-E", "-s", "-c", SMOKE_SCRIPT]


def _is_within(path, root):
    path, root = Path(path).resolve(), Path(root).resolve()
    return path == root or root in path.parents


def read_pyvenv_cfg(env_dir):
    cfg = Path(env_dir) / "pyvenv.cfg"
    if not cfg.is_file():
        raise BootstrapError(f"pyvenv.cfg missing: {cfg}")
    values = {}
    for line in cfg.read_text(encoding="utf-8").splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            values[key.strip().lower()] = value.strip()
    return values


def validate_smoke_report(report, identity, env_dir, repo_root, pyvenv_cfg):
    """Fail closed unless the import came from the exact wheel in the env."""
    env_dir = Path(env_dir).resolve()
    if pyvenv_cfg.get("include-system-site-packages", "").lower() != "false":
        raise BootstrapError("Environment is not isolated (system site-packages enabled)")
    if not (report.get("no_user_site") and report.get("ignore_environment")):
        raise BootstrapError("Smoke did not run with -E -s")
    py_mm = tuple(int(x) for x in report["python_version"].split(".")[:2])
    if py_mm != j1a.PYTHON_MAJOR_MINOR:
        raise BootstrapError(f"Environment Python {report['python_version']} is not 3.14")
    if Path(report["prefix"]).resolve() != env_dir:
        raise BootstrapError(f"Smoke ran outside the generated env: {report['prefix']}")

    module_file = Path(report["module_file"]).resolve()
    if not _is_within(module_file, env_dir) or "site-packages" not in module_file.parts:
        raise BootstrapError(
            f"voyage_character_platform imported from unexpected location: {module_file}"
        )
    if _is_within(module_file, repo_root) and not _is_within(module_file, j1a.output_root(repo_root)):
        raise BootstrapError(f"voyage_character_platform imported from Lab source: {module_file}")

    lab_file = Path(report["lab_probe_file"]).resolve()
    if not _is_within(lab_file, repo_root) or _is_within(lab_file, j1a.output_root(repo_root)):
        raise BootstrapError(f"Lab source did not resolve from the Lab tree: {lab_file}")

    if report["dist_name"] != identity["dependency_name"]:
        raise BootstrapError(f"Wrong distribution name: {report['dist_name']}")
    if report["dist_version"] != identity["dependency_version"]:
        raise BootstrapError(
            f"Wrong distribution version: {report['dist_version']} "
            f"(expected {identity['dependency_version']})"
        )
    if not (report["verify_package_v1_public"] and report["verify_package_v1_module"]):
        raise BootstrapError("verify_package_v1 is not exposed by the installed VCP")

    direct_url = report.get("direct_url") or {}
    if "dir_info" in direct_url:
        raise BootstrapError(f"VCP installed from a directory/editable source: {direct_url}")
    archive_hashes = direct_url.get("archive_info", {}).get("hashes", {})
    if archive_hashes.get("sha256") != identity["wheel_sha256"]:
        raise BootstrapError(f"Installed archive hash differs from provenance: {direct_url}")
    if not str(direct_url.get("url", "")).endswith("/" + identity["wheel_filename"]):
        raise BootstrapError(f"Installed from unexpected archive: {direct_url.get('url')}")

    dists = set(report["distributions"])
    if dists != EXPECTED_ENV_DISTRIBUTIONS:
        raise BootstrapError(f"Unexpected distributions in env: {sorted(dists)}")
    return module_file


def run_smoke(py, repo_root, temp_dir):
    out = j1a.run_cmd(
        smoke_command(py),
        "LAB VCP CONSUMPTION SMOKE",
        env=j1a.subprocess_env(temp_dir=temp_dir),
        cwd=str(repo_root),
    )
    return json.loads(out.strip().splitlines()[-1])


# =============================================================================
# Base interpreter protection
# =============================================================================

BASE_PROBE_SCRIPT = (
    "import importlib.util as u;"
    "print('PRESENT' if u.find_spec('voyage_character_platform') else 'ABSENT')"
)


def base_python_probe_command():
    return [sys.executable, "-I", "-c", BASE_PROBE_SCRIPT]


def assert_base_python_clean():
    out = j1a.run_cmd(
        base_python_probe_command(),
        "BASE PYTHON HAS NO VCP",
        env=j1a.subprocess_env(),
    ).strip()
    if out != "ABSENT":
        raise BootstrapError("voyage_character_platform is importable from the base interpreter")


# =============================================================================
# Orchestration
# =============================================================================


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Create the Lab-local VCP dependency environment (offline)"
    )
    parser.parse_args(argv)

    if sys.version_info[:2] != j1a.PYTHON_MAJOR_MINOR:
        raise BootstrapError(f"Python 3.14 required, running {sys.version.split()[0]}")

    repo_root = j1a.lab_repo_root()
    j1a.validate_repo_root(repo_root)
    identity = load_dependency_identity(provenance_path(repo_root))

    print("=" * 70)
    print(f"LAB VCP ENV: {identity['dependency_name']} {identity['dependency_version']}")
    print(f"Source commit:  {identity['source_commit']}")
    print(f"Wheel SHA-256:  {identity['wheel_sha256']}")
    print("Network:        DISABLED (--no-index)")
    print("=" * 70)
    print()

    assert_base_python_clean()
    wheel = verify_wheel(j1a.output_layout(repo_root)["wheel_path"], identity)

    env_dir = lab_env_dir(repo_root)
    temp_dir = j1a.reset_generated_dir(repo_root, j1a.output_root(repo_root) / "lab_vcp_env_tmp")
    env_dir, py = create_env(repo_root, env_dir, temp_dir)
    install_wheel(py, wheel, temp_dir)

    report = run_smoke(py, repo_root, temp_dir)
    module_file = validate_smoke_report(
        report, identity, env_dir, repo_root, read_pyvenv_cfg(env_dir)
    )
    assert_base_python_clean()

    print()
    print(f"ENV_PYTHON:        {Path(py).relative_to(repo_root).as_posix()}")
    print(f"PYTHON_VERSION:    {report['python_version']}")
    print(f"DISTRIBUTION:      {report['dist_name']} {report['dist_version']}")
    print("VERIFY_PACKAGE_V1: PRESENT")
    print(f"MODULE_ORIGIN:     {module_file.relative_to(repo_root).as_posix()}")
    print(f"ENV_DISTRIBUTIONS: {', '.join(report['distributions'])}")
    print("\nDONE.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except BootstrapError as exc:
        sys.exit(f"LAB VCP ENV FAILED (fail closed): {exc}")