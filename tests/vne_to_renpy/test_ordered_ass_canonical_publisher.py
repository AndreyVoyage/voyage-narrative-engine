TEMP_FIRST_LINE = "# AUTO-GENERATED OrderedASS Ren'Py project candidate."
OWNERSHIP_PREAMBLE = (
    "# VNE-GENERATED: ORDERED_ASS_RENPY_V1\n"
    "# SOURCE: Accepted OrderedASS\n"
    "# DO NOT EDIT: regenerated by the VNE OrderedASS export workflow."
)


def _temp_candidate(scene_id="SC_900", ass_id="ass_900", text="Hello.") -> OrderedProjectCandidate:
    body = SceneBody(
        authoring_schema_version=AUTHORING_SCHEMA_VERSION,
        scene_id=scene_id,
        location_id="yoga_hall",
        participants=(Participant(character_id="KIRA", role="protagonist", present=True),),
        content_rating="PG",
        entries=(TextEntry(entry_id="e1", presentation="NARRATIVE", text=text),),
    )
    ass = build_ordered_ass(body, ass_id=ass_id, version=1, source_ref="x", source_hash="0" * 64)
    tmp = Path(tempfile.mkdtemp(prefix="vne_pub_"))
    reg = tmp / "registry.json"
    reg.write_text('{"assets": []}', encoding="utf-8")
    return build_ordered_project_candidate(
        (ass,), reading_mode="classic_vn", character_symbols={},
        registry_path=reg, repo_root=tmp,
    )


def _prepared_candidate(scene_id="SC_900", ass_id="ass_900", text="Hello.") -> OrderedProjectCandidate:
    return prepare_ordered_candidate_for_canonical_publication(
        _temp_candidate(scene_id=scene_id, ass_id=ass_id, text=text)
    )


def _lint(candidate: OrderedProjectCandidate) -> CandidateLintResult:
    return CandidateLintResult(
        candidate_filename=candidate.candidate_filename,
        candidate_source_sha256=candidate.source_sha256,
        command=("python", "renpy.py", "novel", "lint", "--error-code"),
        returncode=0, stdout="", stderr="", passed=True, temp_cleaned=True,
    )


def _repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    (repo / "novel" / "game").mkdir(parents=True)
    (repo / "novel" / "game" / "scenes_v2_generated.rpy").write_text(
        "label sc_017_v2_start:\n    return\n", encoding="utf-8"
    )
    (repo / "novel" / "game" / "script.rpy").write_text(
        "label start:\n    return\n", encoding="utf-8"
    )
    return repo


def _canonical_path(repo: Path) -> Path:
    return repo / "novel" / "game" / "ordered_ass_generated.rpy"


