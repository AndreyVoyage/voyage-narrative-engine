def test_actual_sdk_final_path_integration(tmp_path):
    sdk_raw = os.environ.get("VNE_TEST_RENPY_SDK_PATH")
    if not sdk_raw:
        pytest.skip("VNE_TEST_RENPY_SDK_PATH not set")
    sdk_path = Path(sdk_raw)

    from tools.renpy_static_validator import find_renpy_command
    from tools.vne_to_renpy import lint_ordered_ass_candidate

    # temp repository fixture: copy the real source novel in (read-only input)
    repo_root = tmp_path / "repo"
    repo_root.mkdir()
    shutil.copytree(_REPO_ROOT / "novel", repo_root / "novel")
    registry_path = _REPO_ROOT / "scenarios" / "visual_assets" / "ASSET_REGISTRY.json"

    def _scene(scene_id, ass_id, entries):
        body = SceneBody(
            authoring_schema_version=AUTHORING_SCHEMA_VERSION,
            scene_id=scene_id,
            location_id="yoga_hall",
            participants=(Participant(character_id="KIRA", role="protagonist", present=True),),
            content_rating="PG",
            entries=entries,
        )
        return build_ordered_ass(body, ass_id=ass_id, version=1, source_ref="x", source_hash="0" * 64)

    scene_a = _scene("SC_900", "ass_900", (
        TextEntry(entry_id="e1", presentation="NARRATIVE", text="Kira enters the yoga hall."),
        ChoiceEntry(entry_id="c1", prompt="Continue?", options=(
            ChoiceOption(option_id="o1", display_text="Continue",
                         target=ChoiceTarget(target_kind="SCENE", target_id="SC_901")),
        )),
        VisualChangeEvent(entry_id="v1", operation="SET", asset_id="kira_yoga_hall_pilot_image_01"),
    ))
    scene_b = _scene("SC_901", "ass_901", (
        TextEntry(entry_id="e1", presentation="NARRATIVE", text="Kira continues."),
        VisualChangeEvent(entry_id="v1", operation="CLEAR", asset_id=None),
    ))

    candidate = build_ordered_project_candidate(
        (scene_a, scene_b),
        reading_mode="classic_vn",
        character_symbols={},
        registry_path=registry_path,
        repo_root=repo_root,
    )
    prepared = prepare_ordered_candidate_for_canonical_publication(candidate)

    lint_result = lint_ordered_ass_candidate(
        prepared,
        source_novel_path=repo_root / "novel",
        sdk_path=sdk_path,
    )
    assert lint_result.passed is True

    publish_result = publish_ordered_project_candidate(
        prepared, lint_result, repo_root=repo_root
    )
    assert publish_result.changed is True

    canonical = repo_root / "novel" / "game" / "ordered_ass_generated.rpy"
    assert canonical.read_bytes() == prepared.source.encode("utf-8")
    assert hashlib.sha256(canonical.read_bytes()).hexdigest() == prepared.source_sha256
    assert (repo_root / "novel" / "game" / "scenes_v2_generated.rpy").exists()

    # run real SDK lint against the temp project with the final canonical file present
    command_info = find_renpy_command(sdk_path)
    assert command_info is not None
    python_exe, renpy_entry = command_info
    if renpy_entry == python_exe:
        cmd = [str(python_exe), str(repo_root / "novel"), "lint", "--error-code"]
    else:
        cmd = [str(python_exe), str(renpy_entry), str(repo_root / "novel"), "lint", "--error-code"]
    env = os.environ.copy()
    env["SDL_VIDEODRIVER"] = "dummy"
    env["SDL_AUDIODRIVER"] = "dummy"
    env["RENPY_PATH_TO_SAVES"] = str(tmp_path / "saves")
    completed = subprocess.run(
        cmd, capture_output=True, text=True, encoding="utf-8",
        errors="replace", env=env, timeout=300,
    )
    assert completed.returncode == 0, completed.stderr

    # real source novel unchanged
    assert not (_REPO_ROOT / "novel" / "game" / "ordered_ass_generated.rpy").exists()
