def test_preparation_requires_temporary_marker():
    bad = OrderedProjectCandidate(
        source="# WRONG first line\n# something\n",
        source_sha256=hashlib.sha256(b"# WRONG first line\n# something\n").hexdigest(),
        scene_ids=("SC_900",), ass_ids=("ass_900",),
        reading_mode="classic_vn", candidate_filename=ORDERED_ASS_CANDIDATE_FILENAME,
    )
    with pytest.raises(OrderedCanonicalPublishError):
        prepare_ordered_candidate_for_canonical_publication(bad)


def test_preparation_ownership_preamble_exact():
    c = _prepared_candidate()
    assert c.source.startswith(OWNERSHIP_PREAMBLE + "\n")


def test_preparation_replaces_only_first_line():
    temp = _temp_candidate()
    prepared = prepare_ordered_candidate_for_canonical_publication(temp)
    expected = OWNERSHIP_PREAMBLE + temp.source[len(TEMP_FIRST_LINE):]
    assert prepared.source == expected


def test_preparation_preserves_metadata():
    c = _prepared_candidate(scene_id="SC_900", ass_id="ass_900")
    assert c.scene_ids == ("SC_900",)
    assert c.ass_ids == ("ass_900",)
    assert c.reading_mode == "classic_vn"
    assert c.candidate_filename == ORDERED_ASS_CANDIDATE_FILENAME


def test_preparation_recomputes_hash():
    c = _prepared_candidate()
    assert c.source_sha256 == hashlib.sha256(c.source.encode("utf-8")).hexdigest()


def test_preparation_deterministic():
    a = _prepared_candidate()
    b = _prepared_candidate()
    assert a.source == b.source
    assert a.source_sha256 == b.source_sha256


def test_preparation_does_not_rerender():
    a = _prepared_candidate(text="Hello.")
    b = _prepared_candidate(text="Goodbye.")
    assert a.source != b.source


