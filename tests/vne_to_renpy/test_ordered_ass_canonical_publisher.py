def test_published_bytes_are_exact_and_lf(tmp_path):
    repo = _repo(tmp_path)
    c = _prepared_candidate()
    _publish(c, _lint(c), repo)
    published = _canonical_path(repo).read_bytes()
    assert published == c.source.encode("utf-8")
    assert b"\r\n" not in published
    assert published.endswith(b"\n")
    assert not published.endswith(b"\n\n")
    assert hashlib.sha256(published).hexdigest() == c.source_sha256
    assert b"2026" not in published  # no timestamp


