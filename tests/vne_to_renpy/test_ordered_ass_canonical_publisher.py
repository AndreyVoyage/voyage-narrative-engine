def _publish(candidate, lint_result, repo):
    return publish_ordered_project_candidate(candidate, lint_result, repo_root=repo)


def test_first_publication_creates(tmp_path):
    repo = _repo(tmp_path)
    c = _prepared_candidate()
    r = _publish(c, _lint(c), repo)
    assert isinstance(r, OrderedCanonicalPublishResult)
    assert r.changed is True
    assert r.replaced_existing is False
    assert r.bytes_written == len(c.source.encode("utf-8"))
    assert _canonical_path(repo).read_bytes() == c.source.encode("utf-8")


