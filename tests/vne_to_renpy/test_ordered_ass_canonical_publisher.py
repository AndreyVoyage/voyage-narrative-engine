def test_same_directory_temp_used(tmp_path, monkeypatch):
    import tools.vne_to_renpy.ordered_ass_canonical_publisher as mod
    real_mkstemp = tempfile.mkstemp
    seen: list[str] = []

    def fake_mkstemp(*args, **kwargs):
        seen.append(kwargs.get("dir", ""))
        return real_mkstemp(*args, **kwargs)

    monkeypatch.setattr(mod.tempfile, "mkstemp", fake_mkstemp)
    repo = _repo(tmp_path)
    c = _prepared_candidate()
    _publish(c, _lint(c), repo)
    assert seen
    assert all(Path(d).resolve() == (repo / "novel" / "game").resolve() for d in seen)


def test_replace_failure_leaves_old_destination_unchanged(tmp_path, monkeypatch):
    repo = _repo(tmp_path)
    c1 = _prepared_candidate(text="One.")
    _publish(c1, _lint(c1), repo)
    c2 = _prepared_candidate(text="Two.")

    def fake_replace(src, dst):
        raise OSError("injected replace failure")

    monkeypatch.setattr(os, "replace", fake_replace)
    with pytest.raises(OrderedCanonicalPublishError):
        _publish(c2, _lint(c2), repo)
    assert _canonical_path(repo).read_bytes() == c1.source.encode("utf-8")
    # no temp artifact left behind
    leftovers = list((repo / "novel" / "game").glob(".ordered_ass_generated.*.tmp"))
    assert leftovers == []


